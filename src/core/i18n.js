export function makeT(lang) {
  const dict = STRINGS[lang] || ar;
  return (key, ...args) => {
    const s = dict[key] !== undefined ? dict[key] : ar[key] !== undefined ? ar[key] : key;
    return args.length ? s.replace(/\{(\d)\}/g, (_m, i) => (args[i] !== undefined ? args[i] : '')) : s;
  };
}
